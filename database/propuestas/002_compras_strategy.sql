-- Ver docs/COMPRAS_REGLAS_NEGOCIO.md. Ejecutar con compras deshabilitado.
-- Una sola ejecución transaccional; no es un script de arranque ni una migración automática.
BEGIN;
ALTER TABLE public.ordenes_compra ALTER COLUMN estado TYPE varchar(30);
-- Solo retirar el CHECK que limita estado, conservando PK/FK/tipo y cualquier otro CHECK.
DO $$
DECLARE c record;
BEGIN
  FOR c IN SELECT conname FROM pg_constraint
    WHERE conrelid='public.ordenes_compra'::regclass AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%estado%'
  LOOP EXECUTE format('ALTER TABLE public.ordenes_compra DROP CONSTRAINT %I',c.conname); END LOOP;
END $$;
ALTER TABLE public.ordenes_compra
  ADD CONSTRAINT compras_estado_check CHECK (estado IN ('PENDIENTE','PENDIENTE_AUTORIZACION','AUTORIZADA','EMITIDA','RECIBIDA','CANCELADA')),
  ADD COLUMN clave_solicitud uuid UNIQUE,
  ADD COLUMN solicitada_por varchar(255),
  ADD COLUMN autorizada_por varchar(255),
  ADD COLUMN fecha_autorizacion timestamptz,
  ADD COLUMN emitida_por varchar(255),
  ADD COLUMN fecha_emision timestamptz,
  ADD CONSTRAINT compras_autorizacion_check CHECK (
    clave_solicitud IS NULL OR (
      solicitada_por IS NOT NULL AND
      (tipo <> 'STOCK_QUINTEROS' OR estado NOT IN ('AUTORIZADA','EMITIDA','RECIBIDA')
        OR (autorizada_por IS NOT NULL AND fecha_autorizacion IS NOT NULL)) AND
      (estado NOT IN ('EMITIDA','RECIBIDA') OR (emitida_por IS NOT NULL AND fecha_emision IS NOT NULL))));

CREATE TABLE public.compras_coberturas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave_solicitud uuid NOT NULL UNIQUE,
  solicitada_por varchar(255) NOT NULL,
  fecha timestamptz NOT NULL,
  orden_compra_id bigint UNIQUE REFERENCES public.ordenes_compra(id)
);
CREATE TABLE public.compras_cobertura_pedidos (
  cobertura_id bigint NOT NULL REFERENCES public.compras_coberturas(id),
  pedido_id bigint NOT NULL UNIQUE REFERENCES public.pedidos(id),
  PRIMARY KEY(cobertura_id,pedido_id)
);
CREATE TABLE public.compras_cobertura_detalles (
  cobertura_id bigint NOT NULL REFERENCES public.compras_coberturas(id),
  producto_id bigint NOT NULL REFERENCES public.productos(id),
  cantidad_stock integer NOT NULL CHECK(cantidad_stock>=0),
  cantidad_abierta integer NOT NULL CHECK(cantidad_abierta>=0),
  PRIMARY KEY(cobertura_id,producto_id)
);
CREATE INDEX compras_estado_idx ON public.ordenes_compra(estado);
CREATE INDEX compras_cobertura_producto_idx ON public.compras_cobertura_detalles(producto_id);
-- Sin acceso directo desde Supabase anon/authenticated. Backend JDBC mantiene permisos
-- de su cuenta configurada; revisar GRANT/RLS con el responsable antes de ejecutar.
ALTER TABLE public.compras_coberturas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.compras_cobertura_pedidos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.compras_cobertura_detalles ENABLE ROW LEVEL SECURITY;
COMMIT;
