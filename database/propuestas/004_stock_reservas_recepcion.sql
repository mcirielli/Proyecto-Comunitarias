-- PROPUESTA: NO EJECUTADA. Modelo aprobado; ejecución y backfill requieren aprobación específica.
-- No ejecutar 001/002 de nuevo. Detener escritores de inventario/compras durante el cambio.
-- Backup completo restaurable y permisos del rol JDBC deben comprobarse antes de ejecutar.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';
LOCK TABLE public.stock,public.movimientos_stock,public.pedidos,public.pedido_detalle,
 public.ordenes_compra,public.orden_compra_detalle,public.compras_coberturas,
 public.compras_cobertura_pedidos,public.compras_cobertura_detalles IN SHARE ROW EXCLUSIVE MODE;
DO $$ BEGIN
 IF to_regclass('public.inventario_asignaciones') IS NOT NULL
 OR to_regclass('public.reservas_pedido') IS NOT NULL
 OR to_regclass('public.inventario_recepciones') IS NOT NULL THEN
  RAISE EXCEPTION '004 ya existe total o parcialmente; detener y revisar';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public'
  AND table_name='ordenes_compra' AND column_name='fecha_emision') THEN
  RAISE EXCEPTION 'Se requiere estructura 002 previamente aplicada';
 END IF;
 IF EXISTS(SELECT 1 FROM public.stock WHERE cantidad_reservada<>0) THEN
  RAISE EXCEPTION 'Reservas agregadas legadas requieren conciliación específica';
 END IF;
 -- Solo reconstrucción demostrable de lotes de un pedido, sin stock histórico asignado,
 -- cuyo origen es su propia orden emitida. No reconstruir orígenes ambiguos.
 IF EXISTS(SELECT 1 FROM public.compras_cobertura_detalles a
  JOIN public.compras_coberturas c ON c.id=a.cobertura_id
  WHERE a.cantidad_stock<>0 OR
   (SELECT count(*) FROM public.compras_cobertura_pedidos p WHERE p.cobertura_id=c.id)<>1 OR
   NOT EXISTS(SELECT 1 FROM public.ordenes_compra o JOIN public.orden_compra_detalle d ON d.orden_compra_id=o.id
     WHERE o.id=c.orden_compra_id AND o.estado='EMITIDA' AND d.producto_id=a.producto_id AND d.cantidad>=a.cantidad_abierta) OR
   NOT EXISTS(SELECT 1 FROM public.compras_cobertura_pedidos cp JOIN public.pedidos p ON p.id=cp.pedido_id
     JOIN public.pedido_detalle d ON d.pedido_id=p.id WHERE cp.cobertura_id=c.id AND p.estado='CONFIRMADO'
     AND d.producto_id=a.producto_id AND d.cantidad=a.cantidad_abierta)) THEN
  RAISE EXCEPTION 'Ledger histórico ambiguo o avanzado; no ejecutar backfill automático';
 END IF;
 IF EXISTS(SELECT 1 FROM public.compras_cobertura_pedidos cp JOIN public.pedido_detalle pd ON pd.pedido_id=cp.pedido_id
  WHERE NOT EXISTS(SELECT 1 FROM public.compras_cobertura_detalles cd WHERE cd.cobertura_id=cp.cobertura_id AND cd.producto_id=pd.producto_id)) THEN
  RAISE EXCEPTION 'Ledger histórico incompleto';
 END IF;
END $$;
ALTER TABLE public.stock ADD CONSTRAINT stock_existencia_limite CHECK(cantidad_disponible::bigint+cantidad_reservada::bigint<=2147483647);
CREATE UNIQUE INDEX inventario_ingreso_unico ON public.movimientos_stock(orden_compra_id,producto_id)
 WHERE tipo='INGRESO' AND orden_compra_id IS NOT NULL;
CREATE UNIQUE INDEX inventario_pedido_movimiento_unico ON public.movimientos_stock(pedido_id,producto_id,tipo)
 WHERE tipo IN ('RESERVA','EGRESO') AND pedido_id IS NOT NULL;
CREATE TABLE public.inventario_recepciones(
 orden_compra_id bigint PRIMARY KEY REFERENCES public.ordenes_compra(id),
 actor varchar(255) NOT NULL,fecha timestamptz NOT NULL
);
CREATE TABLE public.reservas_pedido(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id bigint NOT NULL REFERENCES public.pedidos(id),producto_id bigint NOT NULL REFERENCES public.productos(id),
 cantidad integer NOT NULL CHECK(cantidad>0),consumida boolean NOT NULL DEFAULT false,
 fecha timestamptz NOT NULL,actor varchar(255) NOT NULL,fecha_consumo timestamptz,
 UNIQUE(pedido_id,producto_id),CHECK(consumida=(fecha_consumo IS NOT NULL))
);
CREATE TABLE public.inventario_asignaciones(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cobertura_id bigint NOT NULL REFERENCES public.compras_coberturas(id),
 pedido_id bigint NOT NULL REFERENCES public.pedidos(id),producto_id bigint NOT NULL REFERENCES public.productos(id),
 orden_compra_id bigint REFERENCES public.ordenes_compra(id),cantidad integer NOT NULL CHECK(cantidad>0),
 fase varchar(20) NOT NULL CHECK(fase IN ('ABIERTA','FISICA','RESERVADA','CONSUMIDA')),
 fecha_asignacion timestamptz NOT NULL,fecha_recepcion timestamptz,fecha_reserva timestamptz,fecha_consumo timestamptz,
 FOREIGN KEY(cobertura_id,pedido_id) REFERENCES public.compras_cobertura_pedidos(cobertura_id,pedido_id),
 CHECK(fase<>'ABIERTA' OR (orden_compra_id IS NOT NULL AND fecha_recepcion IS NULL)),
 CHECK(fase NOT IN ('RESERVADA','CONSUMIDA') OR fecha_reserva IS NOT NULL),
 CHECK((fase='CONSUMIDA')=(fecha_consumo IS NOT NULL))
);
CREATE UNIQUE INDEX inventario_origen_fisico_unico ON public.inventario_asignaciones(pedido_id,producto_id) WHERE orden_compra_id IS NULL;
CREATE UNIQUE INDEX inventario_origen_orden_unico ON public.inventario_asignaciones(pedido_id,producto_id,orden_compra_id) WHERE orden_compra_id IS NOT NULL;
CREATE INDEX inventario_asignacion_producto ON public.inventario_asignaciones(producto_id,fase);
CREATE INDEX inventario_asignacion_orden ON public.inventario_asignaciones(orden_compra_id);
CREATE INDEX inventario_movimiento_producto ON public.movimientos_stock(producto_id,fecha DESC,id DESC);
INSERT INTO public.inventario_asignaciones(cobertura_id,pedido_id,producto_id,orden_compra_id,cantidad,fase,fecha_asignacion)
 SELECT c.id,cp.pedido_id,d.producto_id,c.orden_compra_id,d.cantidad_abierta,'ABIERTA',c.fecha
 FROM public.compras_coberturas c JOIN public.compras_cobertura_pedidos cp ON cp.cobertura_id=c.id
 JOIN public.compras_cobertura_detalles d ON d.cobertura_id=c.id WHERE d.cantidad_abierta>0;
-- No se crean reservas/movimientos ni se cambia estado/saldo de datos anteriores.
ALTER TABLE public.inventario_recepciones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reservas_pedido ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inventario_asignaciones ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.inventario_recepciones,public.reservas_pedido,public.inventario_asignaciones FROM PUBLIC;
DO $$ DECLARE rol text; BEGIN
 FOREACH rol IN ARRAY ARRAY['anon','authenticated'] LOOP
  IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=rol) THEN
   EXECUTE format('REVOKE ALL ON public.inventario_recepciones, public.reservas_pedido, public.inventario_asignaciones FROM %I',rol);
  END IF;
 END LOOP;
END $$;
COMMIT;
